export type RegionSmoothOptions = {
  /** Rings inside the border also held (softer each ring in): how much of the patch's edge keeps its form. g3's nConstrainLoops. */
  rings?: number;
  /** The border's hold (g3's default 10). */
  borderWeight?: number;
  /** A soft hold on every other corner (0: none - the smoothest surface; more keeps more of the shape). */
  interiorWeight?: number;
  /** The most conjugate-gradient steps. */
  maxIterations?: number;
};

/**
 * Smooths the corners of the chosen triangles in place. `points`: x y z per corner; `triangles`: three
 * corners each; `chosen`: a flag per triangle. Returns how many corners moved.
 */
export function regionSmooth(points: Float64Array, triangles: ArrayLike<number>, chosen: Uint8Array, options: RegionSmoothOptions = {}): number {
  const rings = Math.max(0, Math.round(options.rings ?? 2));
  const borderWeight = options.borderWeight ?? 10;
  const interiorWeight = options.interiorWeight ?? 0;
  const maxIterations = options.maxIterations ?? 400;
  const cornerCount = points.length / 3;
  // The patch's corners, numbered locally, and which of them also belong to a triangle not chosen (its border).
  const local = new Int32Array(cornerCount).fill(-1);
  const inOther = new Uint8Array(cornerCount);
  const ids: number[] = [];
  for (let t = 0; t * 3 + 2 < triangles.length; t += 1) {
    for (let k = 0; k < 3; k += 1) {
      const c = triangles[t * 3 + k];
      if (chosen[t]) { if (local[c] < 0) { local[c] = ids.length; ids.push(c); } } else inOther[c] = 1;
    }
  }
  const n = ids.length;
  if (n < 4) return 0;
  // Neighbours within the patch.
  const nb: Array<Set<number>> = Array.from({ length: n }, () => new Set<number>());
  for (let t = 0; t * 3 + 2 < triangles.length; t += 1) {
    if (!chosen[t]) continue;
    const a = local[triangles[t * 3]], b = local[triangles[t * 3 + 1]], c = local[triangles[t * 3 + 2]];
    nb[a].add(b); nb[a].add(c); nb[b].add(a); nb[b].add(c); nb[c].add(a); nb[c].add(b);
  }
  const start = new Int32Array(n + 1);
  for (let i = 0; i < n; i += 1) start[i + 1] = start[i] + nb[i].size;
  const col = new Int32Array(start[n]), val = new Float64Array(start[n]), diag = new Float64Array(n);
  for (let i = 0; i < n; i += 1) {
    let k = start[i], sum = 0;
    for (const j of nb[i]) {
      const w = -1 / Math.sqrt(nb[i].size + nb[j].size);
      col[k] = j; val[k] = w; sum += w; k += 1;
    }
    diag[i] = -sum;
  }
  // The constraints: border, then rings in, each the square root of the one outside.
  const weight = new Float64Array(n);
  const held = new Uint8Array(n);
  let layer: number[] = [];
  for (let i = 0; i < n; i += 1) if (inOther[ids[i]]) { weight[i] = borderWeight; held[i] = 1; layer.push(i); }
  if (layer.length) {
    let w = Math.sqrt(borderWeight);
    const seen = new Uint8Array(n);
    for (const i of layer) seen[i] = 1;
    for (let r = 0; r < rings; r += 1) {
      const next: number[] = [];
      for (const i of layer) for (let k = start[i]; k < start[i + 1]; k += 1) {
        const j = col[k];
        if (seen[j]) continue;
        seen[j] = 1;
        weight[j] = w;
        next.push(j);
      }
      layer = next;
      w = Math.sqrt(w);
    }
  }
  if (interiorWeight > 0) for (let i = 0; i < n; i += 1) if (weight[i] === 0) weight[i] = interiorWeight;
  // Normal equations: A = L L + W^2 (L symmetric), b = W^2 c.
  const w2 = new Float64Array(n);
  for (let i = 0; i < n; i += 1) w2[i] = weight[i] * weight[i];
  const tmp = new Float64Array(n);
  const applyL = (x: Float64Array, out: Float64Array) => {
    for (let i = 0; i < n; i += 1) { let s = diag[i] * x[i]; for (let k = start[i]; k < start[i + 1]; k += 1) s += val[k] * x[col[k]]; out[i] = s; }
  };
  const applyA = (x: Float64Array, out: Float64Array) => {
    applyL(x, tmp);
    applyL(tmp, out);
    for (let i = 0; i < n; i += 1) out[i] += w2[i] * x[i];
  };
  // Jacobi preconditioner: the diagonal of L L + W^2.
  const pre = new Float64Array(n);
  for (let i = 0; i < n; i += 1) {
    let s = diag[i] * diag[i];
    for (let k = start[i]; k < start[i + 1]; k += 1) s += val[k] * val[k];
    pre[i] = 1 / (s + w2[i]);
  }
  const x = new Float64Array(n), b = new Float64Array(n), r = new Float64Array(n), z = new Float64Array(n), p = new Float64Array(n), ap = new Float64Array(n);
  for (let axis = 0; axis < 3; axis += 1) {
    for (let i = 0; i < n; i += 1) { x[i] = points[ids[i] * 3 + axis]; b[i] = w2[i] * x[i]; }
    applyA(x, ap);
    let rz = 0, bb = 0;
    for (let i = 0; i < n; i += 1) { r[i] = b[i] - ap[i]; z[i] = pre[i] * r[i]; p[i] = z[i]; rz += r[i] * z[i]; bb += b[i] * b[i]; }
    const tolerance = 1e-12 * Math.max(bb, 1e-12);
    for (let it = 0; it < maxIterations; it += 1) {
      applyA(p, ap);
      let pap = 0;
      for (let i = 0; i < n; i += 1) pap += p[i] * ap[i];
      if (!(pap > 0)) break;
      const alpha = rz / pap;
      let rr = 0;
      for (let i = 0; i < n; i += 1) { x[i] += alpha * p[i]; r[i] -= alpha * ap[i]; rr += r[i] * r[i]; }
      if (rr < tolerance) break;
      let rzNext = 0;
      for (let i = 0; i < n; i += 1) { z[i] = pre[i] * r[i]; rzNext += r[i] * z[i]; }
      const beta = rzNext / rz;
      rz = rzNext;
      for (let i = 0; i < n; i += 1) p[i] = z[i] + beta * p[i];
    }
    // The border snapped back exactly (g3's bForceToFixedPos).
    for (let i = 0; i < n; i += 1) if (!held[i]) points[ids[i] * 3 + axis] = x[i];
  }
  let moved = 0;
  for (let i = 0; i < n; i += 1) if (!held[i]) moved += 1;
  return moved;
}
